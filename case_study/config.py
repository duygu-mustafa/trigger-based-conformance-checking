STATE_COLUMNS = {
    ("mandatory", "violated"): "mandatory_violated_constraints",
    ("mandatory", "satisfied"): "mandatory_satisfied_constraints",
    ("mandatory", "vacuous"): "mandatory_vacuous_constraints",
    ("info", "violated"): "info_violated_constraints",
    ("info", "satisfied"): "info_satisfied_constraints",
    ("info", "vacuous"): "info_vacuous_constraints",
}

GROUP_BY_FILE = {
    "readiness_assessment": "Readiness assessment",
    "sbt_execution": "SBT execution",
    "failure_correction": "Failure correction",
}


def load_constraint_meta() -> pd.DataFrame:
    """id -> label, template, outcome_scope, model group, from configs/declare/*.yaml.

    Extends `load_constraint_labels()` in derive/statistical_analysis.py with the
    metadata fields the results section needs (template, scope, model group).
    """
    rows = []
    for cfg in sorted(DECLARE_DIR.glob("*.yaml")):
        if cfg.stem == "weights":
            continue
        data = yaml.safe_load(cfg.read_text(encoding="utf-8")) or {}
        constraints = (
            data.get("constraints") or data.get("model", {}).get("constraints") or []
        )
        for c in constraints:
            if not isinstance(c, dict) or not c.get("id"):
                continue
            rows.append(
                {
                    "constraint_id": str(c["id"]),
                    "label": str(c.get("label") or c["id"]),
                    "template": str(c.get("template") or ""),
                    "outcome_scope": str(c.get("outcome_scope") or "same_episode"),
                    "model_group": GROUP_BY_FILE.get(cfg.stem, cfg.stem),
                    "config_file": cfg.name,
                }
            )
    return pd.DataFrame(rows)


def explode_states(df: pd.DataFrame) -> pd.DataFrame:
    """Long form: one row per (episode, constraint) with severity and state.

    Expects `stay_id`, `episode_index`, `outcome_binary`, `next_outcome_binary` plus
    the six semicolon-separated constraint-list columns in STATE_COLUMNS.
    """
    frames = []
    for (severity, state), col in STATE_COLUMNS.items():
        if col not in df.columns:
            continue
        part = df[
            ["stay_id", "episode_index", "outcome_binary", "next_outcome_binary", col]
        ].copy()
        part[col] = part[col].fillna("").astype(str)
        part = part[part[col] != ""]
        part["constraint_id"] = part[col].str.split(";")
        part = part.explode("constraint_id")
        part["constraint_id"] = part["constraint_id"].str.strip()
        part = part[part["constraint_id"] != ""]
        part["severity"] = severity
        part["state"] = state
        frames.append(part.drop(columns=[col]))
    return pd.concat(frames, ignore_index=True)


def quantile_summary(series, label: str) -> dict:
    """min/q1/median/mean/q3/p95/max of a numeric series, as a plain dict."""
    s = series.dropna()
    return {
        "metric": label,
        "n": int(s.size),
        "min": float(s.min()) if s.size else None,
        "q1": float(s.quantile(0.25)) if s.size else None,
        "median": float(s.median()) if s.size else None,
        "mean": float(s.mean()) if s.size else None,
        "q3": float(s.quantile(0.75)) if s.size else None,
        "p95": float(s.quantile(0.95)) if s.size else None,
        "max": float(s.max()) if s.size else None,
    }
