def se3_figure_and_table() -> pd.DataFrame:
    df = pd.read_csv(DATA_DIR / "se3_association.csv")
    default = df[df["vacuity_mode"] == "activated_only"]

    agg = (
        default.groupby(["scope", "rule_id", "planted_rr"])
        .agg(
            rr_median=("rr_point", "median"),
            rr_lo=("rr_point", lambda s: s.quantile(0.1)),
            rr_hi=("rr_point", lambda s: s.quantile(0.9)),
            coverage=("ci_covers_planted", "mean"),
            power=("significant", "mean"),
            bias=("log_ratio_to_planted", "mean"),
            n=("n_analysed", "mean"),
            seeds=("seed", "nunique"),
        )
        .reset_index()
    )

    fig, ax = plt.subplots(figsize=(FIG_WIDTH, 3.0))
    rules = sorted(agg["rule_id"].unique())
    x = np.arange(len(rules))
    offset = 0.16

    for scope, color, marker, dx in (
        ("episode", EPISODE_COLOR, "o", -offset),
        ("case", CASE_COLOR, "s", offset),
    ):
        sub = agg[agg["scope"] == scope].set_index("rule_id").loc[rules]
        lo = (sub["rr_median"] - sub["rr_lo"]).clip(lower=0)
        hi = (sub["rr_hi"] - sub["rr_median"]).clip(lower=0)
        ax.errorbar(
            x + dx, sub["rr_median"], yerr=[lo, hi], fmt=marker, color=color,
            capsize=3, markersize=5, label=f"{scope}-scoped estimate", linestyle="none",
        )

    planted = agg.drop_duplicates("rule_id").set_index("rule_id").loc[rules, "planted_rr"]
    ax.scatter(x, planted, marker="_", s=300, color="black", zorder=5, label="planted value")

    ax.set_yscale("log")
    ax.axhline(1.0, color="grey", linewidth=0.8, linestyle="--")
    ticks = sorted({0.25, 0.5, 1.0, 1.5, 2.0, 3.0} | set(planted))
    ax.set_yticks(ticks)
    ax.set_yticklabels([f"{t:g}" for t in ticks])
    ax.minorticks_off()
    ax.set_xticks(x, rules)
    ax.set_ylabel("Risk ratio of success under violation")
    ax.grid(axis="x", visible=False)
    handles, labels = ax.get_legend_handles_labels()
    # Planted value first, then the two estimates.
    order = [labels.index("planted value"), labels.index("episode-scoped estimate"),
             labels.index("case-scoped estimate")]
    fig.legend([handles[i] for i in order], [labels[i] for i in order],
               loc="outside upper center", ncol=3, frameon=False)
    save_fig(fig, "synthetic_association")

    # LaTeX table: episode scope against case scope, per rule.
    ep = agg[agg["scope"] == "episode"].set_index("rule_id")
    ca = agg[agg["scope"] == "case"].set_index("rule_id")
    lines = [
        "% generated by evaluation/synthetic_analysis.py",
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Episode-scoped} & \multicolumn{3}{c}{Case-scoped} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
        r"Rule & Planted $\mathit{RR}$ & $\widehat{\mathit{RR}}$ & Coverage & Power "
        r"& $\widehat{\mathit{RR}}$ & Coverage & Power \\",
        r"\midrule",
    ]
    for rid in rules:
        lines.append(
            f"{rid} & {ep.loc[rid, 'planted_rr']:.2f} & {ep.loc[rid, 'rr_median']:.2f} "
            f"& \\SI{{{100 * ep.loc[rid, 'coverage']:.0f}}}{{\\percent}} "
            f"& \\SI{{{100 * ep.loc[rid, 'power']:.0f}}}{{\\percent}} "
            f"& {ca.loc[rid, 'rr_median']:.2f} "
            f"& \\SI{{{100 * ca.loc[rid, 'coverage']:.0f}}}{{\\percent}} "
            f"& \\SI{{{100 * ca.loc[rid, 'power']:.0f}}}{{\\percent}} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    path = FIG_DIR / "table_se3_recovery.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  table  -> {path}")

    # Vacuity treatment against ground truth, episode scope only.
    vac = (
        df[df["scope"] == "episode"]
        .groupby(["vacuity_mode", "rule_id", "planted_rr"])
        .agg(rr_median=("rr_point", "median"), coverage=("ci_covers_planted", "mean"))
        .reset_index()
    )
    vac.to_csv(DATA_DIR / "se3_vacuity_summary.csv", index=False)
    print(f"  csv    -> {DATA_DIR / 'se3_vacuity_summary.csv'}")
    return agg


def main() -> None:
    print("[synthetic] building figures and tables", flush=True)
    se1_table()
    se2 = se2_figure()
    se3 = se3_figure_and_table()

    print("\nSE2 summary (mean over seeds, multi-episode cases):")
    print(se2[["rule_id", "expected_effect", "episode_acc", "case_acc", "masked", "false_alarm"]]
          .round(3).to_string(index=False))
    print("\nSE3 summary (activated-only vacuity treatment):")
    print(se3[["scope", "rule_id", "planted_rr", "rr_median", "coverage", "power"]]
          .round(3).to_string(index=False))


if __name__ == "__main__":
    main()
