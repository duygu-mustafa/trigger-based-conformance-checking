"""Figures and LaTeX fragments for the synthetic ground-truth experiments.

Reads the CSVs written by ``benchmark_synthetic.py`` and produces:

* ``synthetic_scoping.{pdf,png}`` — SE2, what case-scoped checking does to a
  multi-episode log: violations it hides, violations it invents.
* ``synthetic_association.{pdf,png}`` — SE3, planted against estimated risk
  ratios under both scopes.
* ``table_se1_correctness.tex`` — SE1, verdict correctness per template family.
* ``table_se3_recovery.tex`` — SE3, recovery and interval coverage per rule.

Figures land in ``evaluation/figures``; copy the PDFs into the thesis tree.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

DATA_DIR = REPO_ROOT / "evaluation" / "data" / "synthetic"
FIG_DIR = REPO_ROOT / "evaluation" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)

# The thesis figure style (text width, serif, legend on top) lives with the case
# study; importing it applies the shared rcParams.
sys.path.insert(0, str(REPO_ROOT / "case_study"))
from config import FIG_WIDTH  # noqa: E402

EPISODE_COLOR = "#0072B2"
CASE_COLOR = "#E69F00"
HIDDEN_COLOR = "#CC79A7"
INVENTED_COLOR = "#D55E00"


def legend_above(ax) -> None:
    """Frameless legend centred above one panel."""
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=2, frameon=False)


def save_fig(fig, name: str) -> None:
    # Constrained layout keeps a figure drawn at FIG_WIDTH exactly that wide.
    fig.set_layout_engine("constrained")
    for ext in ("png", "pdf"):
        fig.savefig(FIG_DIR / f"{name}.{ext}")
    plt.close(fig)
    print(f"  figure -> {FIG_DIR / name}.{{png,pdf}}")


# ---------------------------------------------------------------------------
# SE1
# ---------------------------------------------------------------------------

def se1_table() -> None:
    df = pd.read_csv(DATA_DIR / "se1_correctness.csv")
    # Thesis convention: CamelCase template names in small caps (prelim.tex).
    df["group"] = df["template"].replace({"Existence": "AtLeastOne"}).str.replace(r"[ -]", "", regex=True)
    summary = (
        df.groupby("group")
        .agg(
            cases=("match", "size"),
            matching=("match", "sum"),
            deviations=("documented_deviation", lambda s: int((s & ~df.loc[s.index, "match"]).sum())),
        )
        .reset_index()
        .sort_values("group")
    )

    lines = [
        "% generated by evaluation/synthetic_analysis.py",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Template & Cases & Matching & Deviations \\",
        r"\midrule",
    ]
    for _, row in summary.iterrows():
        lines.append(
            f"\\textsc{{{row['group']}}} & \\num{{{row['cases']}}} & \\num{{{row['matching']}}} "
            f"& \\num{{{row['deviations']}}} \\\\"
        )
    total = summary[["cases", "matching", "deviations"]].sum()
    lines += [
        r"\midrule",
        f"Total & \\num{{{total['cases']}}} & \\num{{{total['matching']}}} "
        f"& \\num{{{total['deviations']}}} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    path = FIG_DIR / "table_se1_correctness.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  table  -> {path}")

    unexplained = df[(~df["match"]) & (~df["documented_deviation"])]
    print(f"  SE1: {int(df['match'].sum())}/{len(df)} match, "
          f"{len(unexplained)} unexplained mismatch(es)")


